struct period_g4_result_t {
    double tr_commQ;
    double tr_commQ_powers[8];
    double f_invariants[4];
    double odd_traces[4];
    double worst_odd_rel;
    double thm1_resid_max;     // ||R - 16 U[U,Q]U'||_inf / ||R||_inf
    double R_norm_inf;
    int    ok_theorem1;
};

extern "C" void period_g4_audit(double z, double tol, period_g4_result_t *out) {
    double M[N2], Mp[N2], Mpp[N2];
    compute_M<double>(z, M);
    compute_Mp<double>(z, Mp);
    compute_Mpp(z, Mpp);

    double MM[N2], tmp[N2], Q[N2];
    m8_mul(M, M, MM); m8_add(Mp, MM, tmp); m8_neg(tmp, Q);
    double UQ[N2], QU[N2], commQ[N2];
    m8_mul(M, Q, UQ); m8_mul(Q, M, QU); m8_sub(UQ, QU, commQ);

    double pwrs[9][N2];
    for (int i = 0; i < N2; i++) pwrs[1][i] = commQ[i];
    for (int k = 2; k <= 8; k++) m8_mul(pwrs[k-1], commQ, pwrs[k]);

    out->tr_commQ = m8_trace(commQ);
    for (int k = 1; k <= 8; k++) out->tr_commQ_powers[k-1] = m8_trace(pwrs[k]);
    out->f_invariants[0] = out->tr_commQ_powers[1];
    out->f_invariants[1] = out->tr_commQ_powers[3];
    out->f_invariants[2] = out->tr_commQ_powers[5];
    out->f_invariants[3] = out->tr_commQ_powers[7];
    out->odd_traces[0] = out->tr_commQ_powers[0];
    out->odd_traces[1] = out->tr_commQ_powers[2];
    out->odd_traces[2] = out->tr_commQ_powers[4];
    out->odd_traces[3] = out->tr_commQ_powers[6];
    double scale = 0.0;
    for (int i = 0; i < 4; i++) { double v = std::fabs(out->f_invariants[i]); if (v > scale) scale = v; }
    if (scale < 1.0) scale = 1.0;
    double worst = 0.0;
    for (int i = 0; i < 4; i++) {
        double r = std::fabs(out->odd_traces[i]) / scale;
        if (r > worst) worst = r;
    }
    out->worst_odd_rel = worst;

    // ---- Full Theorem 1 entry-wise: R = (A+S')^2 - 2(D+S)(D+2S)^2 = 16 U[U,Q]U' ----
    double MpU[N2], UMp[N2], tmp2[N2], Qp[N2];
    m8_mul(Mp, M, MpU); m8_mul(M, Mp, UMp);
    m8_add(Mpp, MpU, tmp); m8_add(tmp, UMp, tmp2); m8_neg(tmp2, Qp);  // Q' = -(M'' + M'M + MM')

    double D[N2], A[N2], S[N2], Sp[N2];
    m8_sub(MM, Q, D); for (int i = 0; i < N2; i++) D[i] *= 2.0;
    for (int i = 0; i < N2; i++) A[i]  = -4.0*UMp[i] - 2.0*Qp[i];
    for (int i = 0; i < N2; i++) S[i]  = 2.0*Q[i];
    for (int i = 0; i < N2; i++) Sp[i] = 2.0*Qp[i];
    double in1[N2], in2[N2], in3[N2];
    m8_add(A, Sp, in1); m8_add(D, S, in2);
    for (int i = 0; i < N2; i++) in3[i] = D[i] + 2.0*S[i];
    double in1sq[N2], in3sq[N2], prod[N2], R[N2];
    m8_mul(in1, in1, in1sq); m8_mul(in3, in3, in3sq); m8_mul(in2, in3sq, prod);
    for (int i = 0; i < N2; i++) R[i] = in1sq[i] - 2.0*prod[i];
    double cQ_Mp[N2], U_cQ_Mp[N2];
    m8_mul(commQ, Mp, cQ_Mp); m8_mul(M, cQ_Mp, U_cQ_Mp);
    double resid[N2];
    for (int i = 0; i < N2; i++) resid[i] = R[i] - 16.0*U_cQ_Mp[i];
    out->R_norm_inf = m8_max_abs(R);
    double r_inf = m8_max_abs(resid);
    out->thm1_resid_max = (out->R_norm_inf > 0.0) ? (r_inf / out->R_norm_inf) : r_inf;
    out->ok_theorem1 = (out->thm1_resid_max < tol);
}

