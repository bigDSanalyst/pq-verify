constexpr int N  = 8;
constexpr int N2 = N * N;

template<typename T>
static inline void m8_mul(const T *A, const T *B, T *C) {
    for (int i = 0; i < N; i++)
        for (int j = 0; j < N; j++) {
            T s = T(0);
            for (int k = 0; k < N; k++) s += A[i*N + k] * B[k*N + j];
            C[i*N + j] = s;
        }
}
template<typename T>
static inline void m8_neg(const T *A, T *C) { for (int i = 0; i < N2; i++) C[i] = -A[i]; }
template<typename T>
static inline void m8_sub(const T *A, const T *B, T *C) { for (int i = 0; i < N2; i++) C[i] = A[i] - B[i]; }
template<typename T>
static inline void m8_add(const T *A, const T *B, T *C) { for (int i = 0; i < N2; i++) C[i] = A[i] + B[i]; }
template<typename T>
static inline T m8_trace(const T *A) {
    T s = T(0);
    for (int i = 0; i < N; i++) s += A[i*N + i];
    return s;
}
static inline double m8_max_abs(const double *A) {
    double m = 0.0;
    for (int i = 0; i < N2; i++) { double v = std::fabs(A[i]); if (v > m) m = v; }
    return m;
}

